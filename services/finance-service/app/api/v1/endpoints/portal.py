from __future__ import annotations

import uuid
from fastapi import APIRouter, Depends, HTTPException
from fastapi.responses import PlainTextResponse
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.api.v1.endpoints.health import get_db
from app.domain.models import Invoice, Payment, Receipt, StudentFinancialAccount
from app.schemas.finance import InvoiceOut, ReceiptOut, StudentFinancialAccountOut
from app.security.auth import Principal, require_scoped_roles
from app.services.invoice_service import InvoiceService

router = APIRouter(prefix="/portal", tags=["Student Finance Portal"])


@router.get("/overview")
@router.get("/my-account")
def get_student_portal_overview(
    db: Session = Depends(get_db),
    principal: Principal = Depends(require_scoped_roles("finance.portal.read", "student", "admin")),
):
    svc = InvoiceService(db)
    account = svc.get_or_create_account(principal.user_id)
    invoices = db.scalars(
        select(Invoice)
        .where(Invoice.student_user_id == principal.user_id)
        .order_by(Invoice.created_at.desc())
    ).all()

    return {
        "account": StudentFinancialAccountOut.model_validate(account),
        "invoices_count": len(invoices),
        "unpaid_invoices_count": sum(i.status in {"ISSUED", "PARTIALLY_PAID", "OVERDUE"} for i in invoices),
        "total_outstanding": str(account.outstanding_balance),
        "total_paid": str(account.total_paid),
    }


@router.get("/invoices", response_model=list[InvoiceOut])
def get_student_portal_invoices(
    db: Session = Depends(get_db),
    principal: Principal = Depends(require_scoped_roles("finance.portal.read", "student", "admin")),
):
    query = (
        select(Invoice)
        .where(Invoice.student_user_id == principal.user_id)
        .order_by(Invoice.created_at.desc())
    )
    return list(db.scalars(query).all())


@router.get("/invoices/{id}", response_model=InvoiceOut)
def get_student_portal_invoice_detail(
    id: uuid.UUID,
    db: Session = Depends(get_db),
    principal: Principal = Depends(require_scoped_roles("finance.portal.read", "student", "admin")),
):
    inv = db.get(Invoice, id)
    if not inv or inv.student_user_id != principal.user_id:
        raise HTTPException(status_code=404, detail="Invoice not found")
    return inv


@router.get("/receipts", response_model=list[ReceiptOut])
def get_student_portal_receipts(
    db: Session = Depends(get_db),
    principal: Principal = Depends(require_scoped_roles("finance.portal.read", "student", "admin")),
):
    query = (
        select(Receipt)
        .where(Receipt.student_user_id == principal.user_id)
        .order_by(Receipt.issued_at.desc())
    )
    return list(db.scalars(query).all())


@router.get("/receipts/{id}/download")
def download_student_receipt(
    id: uuid.UUID,
    db: Session = Depends(get_db),
    principal: Principal = Depends(require_scoped_roles("finance.portal.read", "student", "admin")),
):
    receipt = db.get(Receipt, id)
    if not receipt or receipt.student_user_id != principal.user_id:
        raise HTTPException(status_code=404, detail="Receipt not found")

    text_receipt = f"""==================================================
           SMART EDUCATION PLATFORM
              OFFICIAL FEE RECEIPT
==================================================
Receipt Number: {receipt.receipt_number}
Issue Date:     {receipt.issued_at.strftime('%Y-%m-%d %H:%M:%S UTC')}
Student ID:     {receipt.student_user_id}
Amount Paid:    {receipt.currency} {receipt.amount}
Payment Ref:    {receipt.receipt_data.get('provider_transaction_id', 'N/A')}
Payment Method: {receipt.receipt_data.get('payment_method', 'N/A')}
Invoice Ref:    {receipt.receipt_data.get('invoice_number', 'N/A')}
--------------------------------------------------
Status: VALID & SETTLED
Electronic copy generated by SmartEdu Finance System.
==================================================
"""
    return PlainTextResponse(
        content=text_receipt,
        headers={"Content-Disposition": f"attachment; filename=receipt-{receipt.receipt_number}.txt"},
    )
