export const PALETTE_MAP: Record<PaletteId, PaletteDefinition> = Object.fromEntries(
  PALETTES.map((p) => [p.id, p])
) as Record<PaletteId, PaletteDefinition>;

export function isValidPalette(value: unknown): value is PaletteId {
  return typeof value === "string" && value in PALETTE_MAP;
}

export function isValidMode(value: unknown): value is ThemeMode {
  return value === "light" || value === "dark";
}
