    def case(name):
        def run(function):
            start = time.monotonic()
            try:
                detail = function()
                record = {"name": name, "status": "PASS", "detail": detail}
            except Exception as exc:
                record = {
                    "name": name,
                    "status": "FAIL",
                    "detail": f"{type(exc).__name__}: {exc}",
                }
            record["seconds"] = round(time.monotonic() - start, 3)
            records.append(record)
            save()
            print(f"{record['status']}: {name}: {record['detail']}", flush=True)

        return run

    def request(role, method, path, data=None, expected=(200, 201, 202, 204), **kwargs):
        client = clients.get(role) or clients[None]
        headers = {"Origin": ORIGIN, **kwargs.pop("headers", {})}
        if role in tokens:
            headers["Authorization"] = f"Bearer {tokens[role]}"
        response = client.request(method, path, json=data, headers=headers, **kwargs)
        assert response.status_code in expected, (
            f"{method} {urlparse(path).path} HTTP {response.status_code}; request={response.headers.get('X-Request-ID')}"
        )
        return response

    def poll(function, predicate, seconds=15):
        end = time.monotonic() + seconds
        while True:
            value = function()
            if predicate(value):
                return value
            if time.monotonic() >= end:
                raise AssertionError(
                    "Expected persisted effect was not observed before deadline"
                )
            time.sleep(0.4)

