"""Exercise the disposable demo through real HTTP, PostgreSQL and RabbitMQ.

Never print credentials, auth/reset tokens or response bodies. This script only
targets the isolated local environment generated by configure_local.py.
"""
from __future__ import annotations

import csv
import io
import json
import secrets as random_secrets
import time
import uuid
from datetime import UTC, datetime, timedelta
from pathlib import Path
from urllib.parse import parse_qs, urlparse
import re
import hashlib
import boto3
from botocore.exceptions import ClientError
from sqlalchemy import create_engine, text as sql_text
from sqlalchemy.engine import make_url
from sqlalchemy.exc import DBAPIError

import httpx
from dotenv import dotenv_values
from smartedu_contracts import InternalTokenSigner

from local_stack import NAMES, ROOT, RUNTIME

BASE = "http://localhost:18080"
ORIGIN = "http://localhost:5173"


def main():
    secrets = json.loads((RUNTIME / "secrets.json").read_text())
    fixtures = json.loads((RUNTIME / "demo-fixtures.json").read_text())
    private_path = RUNTIME / "live-qa.json"
    private = json.loads(private_path.read_text()) if private_path.exists() else {}
    output = ROOT / "artifacts/integration"
    output.mkdir(parents=True, exist_ok=True)
    records, clients, tokens = [], {None: httpx.Client(base_url=BASE, timeout=20)}, {}

    def save():
        (output / "live-results.json").write_text(json.dumps(records, indent=2), encoding="utf-8")
        private_path.write_text(json.dumps(private, indent=2), encoding="utf-8")

    def case(name):
        def run(function):
            start = time.monotonic()
            try:
                detail = function()
                record = {"name": name, "status": "PASS", "detail": detail}
            except Exception as exc:
                record = {"name": name, "status": "FAIL", "detail": f"{type(exc).__name__}: {exc}"}
            record["seconds"] = round(time.monotonic() - start, 3)
            records.append(record)
            save()
            print(f"{record['status']}: {name}: {record['detail']}", flush=True)
        return run

    def request(role, method, path, data=None, expected=(200, 201, 202, 204), **kwargs):
        client = clients.get(role) or clients[None]
        headers = {"Origin": ORIGIN, **kwargs.pop("headers", {})}
        if role in tokens:
            headers["Authorization"] = f"Bearer {tokens[role]}"
        response = client.request(method, path, json=data, headers=headers, **kwargs)
        assert response.status_code in expected, f"{method} {urlparse(path).path} HTTP {response.status_code}; request={response.headers.get('X-Request-ID')}"
        return response

    def poll(function, predicate, seconds=15):
        end = time.monotonic() + seconds
        while True:
            value = function()
            if predicate(value):
                return value
            if time.monotonic() >= end:
                raise AssertionError("Expected persisted effect was not observed before deadline")
            time.sleep(.4)

    for index, name in enumerate(NAMES, 1):
        @case(f"{name}: health and owned migration readiness")
        def readiness(index=index):
            for path in ("health", "ready"):
                assert httpx.get(f"http://127.0.0.1:{8000+index}/{path}", timeout=5).status_code == 200
            return "Both endpoints returned 200 against the migrated PostgreSQL database"

    for role in ("student", "teacher", "admin"):
        @case(f"{role}: real login and cookie security")
        def login(role=role):
            clients[role] = httpx.Client(base_url=BASE, timeout=20)
            password = secrets["DEMO_PASSWORD"] if role == "admin" else secrets[f"{role.upper()}_PASSWORD"]
            response = request(role, "POST", "/api/v1/identity/auth/login", {"email": f"{role}@demo.example.edu", "password": password})
            tokens[role] = response.json()["access_token"]
            assert "refresh_token" not in response.json()
            cookie = response.headers["set-cookie"].lower()
            assert "httponly" in cookie and "samesite=strict" in cookie and "path=/api/v1/identity/auth" in cookie
            assert response.headers.get("Cache-Control", "").startswith("no-store")
            return "Access token in memory; rotating refresh credential is HttpOnly and SameSite=Strict"

    @case("Gateway: cross-service CORS preflights and private route blocking")
    def cors():
        for service in ("academic", "attendance", "scheduling", "notifications", "facilities", "learning", "assessments", "reporting", "platform"):
            response = request(None, "OPTIONS", f"/api/v1/{service}/probe", expected=(204,), headers={"Access-Control-Request-Method": "POST", "Access-Control-Request-Headers": "authorization,content-type,idempotency-key"})
            assert response.headers.get_list("access-control-allow-origin") == [ORIGIN]
            assert "Idempotency-Key" in response.headers.get("access-control-allow-headers", "")
            request(None, "GET", f"/api/v1/{service}/internal/events", expected=(404,))
        denied = request(None, "OPTIONS", "/api/v1/platform/support/tickets", expected=(204,), headers={"Origin": "https://untrusted.example.edu"})
        assert "access-control-allow-origin" not in denied.headers
        return "Nine namespaces support approved preflight; internal routes and untrusted CORS remain unavailable"

    @case("Academic: enrollment, roster and teacher assignment contracts")
    def academic():
        section = fixtures["section"]["id"]
        rows = request("teacher", "GET", f"/api/v1/academic/sections/{section}/roster").json()
        assert fixtures["student"]["id"] in {row["external_user_id"] for row in rows["students"]}
        sections = request("student", "GET", "/api/v1/academic/students/me/sections").json()
        assert section in {row["id"] for row in sections}
        request("student", "POST", "/api/v1/academic/departments", {"code": "DENIED", "name": "Denied"}, expected=(403,))
        return "Real owner relationships work; Student cannot modify the academic catalog"

    @case("Attendance: finalized records, correct summary and write isolation")
    def attendance():
        totals = request("student", "GET", "/api/v1/attendance/students/me/attendance/summary").json()["totals"]
        assert totals["total_considered_sessions"] >= 5 and totals["attendance_percentage"] == 80
        session = fixtures["attendance-2026-10-01"]["id"]
        request("teacher", "PUT", f"/api/v1/attendance/sessions/{session}/records", {"records": [{"student_user_id": fixtures["student"]["id"], "status": "ABSENT"}]}, expected=(409,))
        request("student", "POST", "/api/v1/attendance/sessions", {"section_id": fixtures["section"]["id"], "session_date": "2026-10-20"}, expected=(403,))
        return "Five final records produce 80%; finalized writes and Student writes are rejected"

    @case("Attendance: real owned bulk mark within two seconds")
    def attendance_write():
        if "timing_session" not in private:
            private["timing_session"] = request("teacher", "POST", "/api/v1/attendance/sessions", {"section_id": fixtures["section"]["id"], "session_date": "2026-10-06", "starts_at": "13:00:00", "ends_at": "14:00:00"}).json()
            save()
        path = f"/api/v1/attendance/sessions/{private['timing_session']['id']}/records"
        start = time.monotonic()
        request("teacher", "PUT", path, {"records": [{"student_user_id": fixtures["student"]["id"], "status": "PRESENT"}]})
        elapsed = time.monotonic() - start
        assert elapsed <= 2, f"Bulk mark took {elapsed:.3f}s"
        records = request("teacher", "GET", path).json()
        rows = records.get("records", records.get("items", [])) if isinstance(records, dict) else records
        assert any(row["student_user_id"] == fixtures["student"]["id"] and row["status"] == "PRESENT" for row in rows)
        return f"Real PostgreSQL bulk mark and owner read-back succeeded in {elapsed:.3f}s; disposable session remains OPEN"

    @case("Scheduling: recurring occurrences visible to enrolled Student")
    def scheduling():
        response = request("student", "GET", "/api/v1/scheduling/timetable/me?start_date=2026-10-08&end_date=2026-10-21")
        rows = response.json()
        rows = rows.get("items", []) if isinstance(rows, dict) else rows
        assert any(row["section_id"] == fixtures["section"]["id"] for row in rows)
        return f"{len(rows)} real occurrences returned"

    @case("Learning: PostgreSQL resources, notes and recommendations")
    def learning():
        resources = request("student", "GET", "/api/v1/learning/students/me/resources").json()
        resources = resources.get("items", []) if isinstance(resources, dict) else resources
        notes = next(row for row in resources if row["id"] == fixtures["resource"]["id"])
        assert any(version["text_content"] for version in notes["versions"])
        recommendations = request("student", "GET", "/api/v1/learning/students/me/recommendations").json()
        assert isinstance(recommendations, list) and any(row["resource"]["id"] == notes["id"] for row in recommendations)
        return "Versioned notes and owner-enforced recommendations resolve through signed Academic contracts"

    @case("Learning: private S3 upload/download, validation and ownership")
    def storage():
        if "file_resource" not in private:
            private["file_resource"] = request("teacher", "POST", "/api/v1/learning/resources", {"title": "Demo QA private file", "resource_type": "FILE", "targets": [{"target_type": "SECTION", "target_id": fixtures["section"]["id"]}]}).json()
            save()
        resource_id = private["file_resource"]["id"]
        path = f"/api/v1/learning/resources/{resource_id}"
        content = b"Labelled private integration fixture.\nNo institutional data.\n"
        request("student", "POST", path + "/upload", files={"file": ("fixture.txt", content, "text/plain")}, expected=(403,))
        request("teacher", "POST", path + "/upload", files={"file": ("fixture.pdf", content, "application/pdf")}, expected=(422,))
        request("teacher", "POST", path + "/upload", files={"file": ("fixture.txt", content, "text/plain")}, expected=(201,))
        request("teacher", "POST", path + "/publish", {})
        response = request("student", "GET", path + "/download")
        assert response.content == content
        assert response.headers["X-Content-SHA256"] == hashlib.sha256(content).hexdigest()
        request(None, "GET", path + "/download", expected=(401,))
        env = dotenv_values(RUNTIME / "learning-service.env")
        s3 = boto3.client("s3", endpoint_url=env["S3_ENDPOINT_URL"], aws_access_key_id=env["S3_ACCESS_KEY"], aws_secret_access_key=env["S3_SECRET_KEY"], region_name="us-east-1")
        objects = s3.list_objects_v2(Bucket="learning-resources")["Contents"]
        key = next(row["Key"] for row in objects if resource_id in row["Key"])
        assert httpx.get(f"http://127.0.0.1:59000/learning-resources/{key}", timeout=5).status_code == 403
        try:
            s3.list_objects_v2(Bucket="platform-imports")
            raise AssertionError("Learning credential accessed Platform storage")
        except ClientError as exc:
            assert exc.response["Error"]["Code"] == "AccessDenied"
        return "Real private object round-trip/checksum; anonymous access and cross-service bucket access denied; MIME validation and Student upload denial verified"

    @case("Assessment: safe questions, persisted answers and automatic grading")
    def assessment():
        assignment = fixtures["assessment-assignment"]["id"]
        detail = request("student", "GET", f"/api/v1/assessments/students/me/assignments/{assignment}").json()
        assert "is_correct" not in json.dumps(detail) and "correct_text" not in json.dumps(detail)
        if "attempt" not in private:
            private["attempt"] = request("student", "POST", f"/api/v1/assessments/assignments/{assignment}/attempts", {}).json()
            save()
        attempt = private["attempt"]["id"]
        current = request("student", "GET", f"/api/v1/assessments/attempts/{attempt}").json()
        if current["status"] == "IN_PROGRESS":
            question = detail["questions"][0]
            choice = next(choice for choice in question["choices"] if choice["text"] == "Transactional outbox")
            request("student", "PUT", f"/api/v1/assessments/attempts/{attempt}/answers/{question['id']}", {"selected_choice_id": choice["id"]})
            current = request("student", "POST", f"/api/v1/assessments/attempts/{attempt}/submit", {}).json()
        assert current["status"] == "GRADED" and current["percent"] == 100 and current["score"] == 5
        return "Committed answer graded 5/5 and 100%; answer keys absent from Student read response"

    @case("Facility: approval, overlap rejection and requester isolation")
    def facilities():
        booking = request("admin", "GET", f"/api/v1/facilities/bookings/{fixtures['booking']['id']}").json()
        if booking["status"] == "PENDING":
            booking = request("admin", "POST", f"/api/v1/facilities/bookings/{booking['id']}/approve", {"note": "Disposable demo verification"}).json()
        assert booking["status"] == "APPROVED"
        payload = {key: booking[key] for key in ("facility_id", "starts_at", "ends_at", "attendees", "purpose")}
        request("student", "POST", "/api/v1/facilities/bookings", payload, expected=(409,))
        request("teacher", "GET", f"/api/v1/facilities/bookings/{booking['id']}", expected=(403,))
        return "Approved booking blocks overlaps; unrelated requester receives 403"

    @case("Notification: actual announcement delivery within five seconds")
    def notification():
        title = f"Demo QA notification {uuid.uuid4().hex[:10]}"
        start = time.monotonic()
        request("teacher", "POST", "/api/v1/notifications/teacher/announcements", {"section_id": fixtures["section"]["id"], "title": title, "body": "Disposable integration verification."})
        def inbox():
            rows = request("student", "GET", "/api/v1/notifications/notifications").json()
            return rows.get("items", []) if isinstance(rows, dict) else rows
        rows = poll(inbox, lambda rows: any(row["title"] == title for row in rows), seconds=5)
        notification = next(row for row in rows if row["title"] == title)
        elapsed = time.monotonic() - start
        assert elapsed <= 5
        request("student", "POST", f"/api/v1/notifications/notifications/{notification['id']}/read", {})
        return f"Announcement persisted and reached Student in {elapsed:.3f}s; mark-read succeeded"

    @case("Platform: request idempotency and ticket isolation")
    def platform():
        payload = {"subject": "Demo QA idempotency", "description": "Disposable integration verification."}
        headers = {"Idempotency-Key": str(uuid.uuid4()), "X-Correlation-ID": str(uuid.uuid4())}
        first = request("student", "POST", "/api/v1/platform/support/tickets", payload, headers=headers)
        second = request("student", "POST", "/api/v1/platform/support/tickets", payload, headers=headers)
        assert first.json()["id"] == second.json()["id"], "Retry created a second ticket"
        assert second.headers.get("X-Idempotent-Replay") == "true", "Replay header missing"
        request("student", "POST", "/api/v1/platform/support/tickets", {**payload, "subject": "Changed body"}, headers=headers, expected=(409,))
        request("teacher", "GET", f"/api/v1/platform/support/tickets/{first.json()['id']}", expected=(403,))
        return "Retry returns the same ticket; conflicting body and unrelated requester are rejected"

    @case("Platform: durable health, reindex and signed owner export jobs")
    def jobs():
        for index, name in enumerate(NAMES, 1):
            request("admin", "PUT", f"/api/v1/platform/admin/services/{name}-service", {"service_name": f"{name}-service", "base_url": f"http://127.0.0.1:{8000+index}", "timeout_seconds": 3})
        for payload in ({"job_type": "HEALTH_SWEEP"}, {"job_type": "REINDEX"}, {"job_type": "EXPORT", "target_service": "academic-service", "resource_type": "students", "parameters": {"limit": 100}}):
            job = request("admin", "POST", "/api/v1/platform/admin/jobs", payload).json()
            rows = poll(lambda: request("admin", "GET", "/api/v1/platform/admin/jobs").json(), lambda rows: any(row["id"] == job["id"] and row["status"] in {"COMPLETED", "FAILED"} for row in rows), seconds=70)
            finished = next(row for row in rows if row["id"] == job["id"])
            assert finished["status"] == "COMPLETED", f"{payload['job_type']} failed: {finished['error']}"
            if payload["job_type"] == "HEALTH_SWEEP":
                assert len(finished["result"]["services"]) == 10 and all(row["status"] == "HEALTHY" for row in finished["result"]["services"])
            if payload["job_type"] == "EXPORT":
                assert finished["result"]["items"]
        return "All ten services ready; durable health/reindex/export jobs completed via owner contracts"

    @case("Reporting: RabbitMQ grade projection and actual CSV export")
    def reporting():
        response = poll(lambda: request("admin", "GET", "/api/v1/reporting/reports/assessment.csv"), lambda r: private.get("attempt", {}).get("id", "missing") in r.text, seconds=15)
        rows = list(csv.DictReader(io.StringIO(response.text)))
        assert any(row["attempt_id"] == private["attempt"]["id"] and float(row["percent"]) == 100 for row in rows)
        request("student", "GET", "/api/v1/reporting/reports/assessment.csv", expected=(403,))
        return "Committed grade arrived through broker/inbox and appears in Admin-only CSV"

    @case("Identity: real SMTP recovery, single use and refresh revocation")
    def recovery():
        if "recovery_user" not in private:
            private["recovery_password"] = "K9!" + random_secrets.token_urlsafe(24) + "zQ"
            private["recovery_email"] = f"qa-{uuid.uuid4().hex[:12]}@demo.example.edu"
            private["recovery_user"] = request("admin", "POST", "/api/v1/identity/users", {"email": private["recovery_email"], "full_name": "Integration QA", "role": "student", "password": private["recovery_password"]}).json()
            save()
        clients["qa"] = httpx.Client(base_url=BASE, timeout=20)
        request("qa", "POST", "/api/v1/identity/auth/login", {"email": private["recovery_email"], "password": private["recovery_password"]})
        prior_messages = {row["ID"] for row in httpx.get("http://127.0.0.1:18025/api/v1/messages", timeout=5).json()["messages"]}
        existing = request(None, "POST", "/api/v1/identity/auth/password/forgot", {"email": private["recovery_email"]}, expected=(202,))
        missing = request(None, "POST", "/api/v1/identity/auth/password/forgot", {"email": f"missing-{uuid.uuid4().hex}@example.edu"}, expected=(202,))
        assert existing.json() == missing.json()
        def mail():
            messages = httpx.get("http://127.0.0.1:18025/api/v1/messages", timeout=5).json()["messages"]
            for message in messages:
                if message["ID"] in prior_messages:
                    continue
                if any(recipient["Address"] == private["recovery_email"] for recipient in message["To"]):
                    body = httpx.get(f"http://127.0.0.1:18025/api/v1/message/{message['ID']}", timeout=5).json()
                    match = re.search(r'https?://[^\s<>"\']+/reset-password[#?]token=[A-Za-z0-9_-]+', body.get("Text", "") + body.get("HTML", ""))
                    if match:
                        parsed = urlparse(match.group())
                        return parse_qs(parsed.fragment or parsed.query)["token"][0]
            return None
        token = poll(mail, bool, seconds=15)
        password = "R8!" + random_secrets.token_urlsafe(24) + "mZ"
        request(None, "POST", "/api/v1/identity/auth/password/reset", {"token": token, "new_password": password}, expected=(204,))
        private["recovery_password"] = password
        save()
        request(None, "POST", "/api/v1/identity/auth/password/reset", {"token": token, "new_password": password}, expected=(400,))
        request("qa", "POST", "/api/v1/identity/auth/refresh", {}, expected=(401,))
        request("qa", "POST", "/api/v1/identity/auth/login", {"email": private["recovery_email"], "password": password})
        return "Encrypted outbox delivered a real Mailpit email; reset is single-use and revokes prior refresh session"

    @case("Academic: signed owner import rollback is atomic")
    def atomic_import():
        signer = InternalTokenSigner(service_name="platform-service", private_key_pem=(RUNTIME / "platform-internal-private.pem").read_text())
        token = signer.issue(audience="academic-service", scopes=("academic:data:import",))
        code = "QA-" + uuid.uuid4().hex[:12]
        payload = {"items": [{"code": code, "name": "Demo QA rollback first"}, {"code": code, "name": "Demo QA rollback duplicate"}]}
        response = httpx.post("http://127.0.0.1:8002/api/v1/internal/imports/departments", json=payload, headers={"Authorization": f"Bearer {token}", "Idempotency-Key": str(uuid.uuid4())}, timeout=10)
        assert response.status_code == 409, f"Duplicate import returned HTTP {response.status_code}"
        rows = request("admin", "GET", "/api/v1/academic/departments?limit=100").json()
        assert not any(row["code"] == code for row in rows)
        return "Duplicate batch rejected and its earlier valid row rolled back in Academic's owned transaction"

    @case("Security: ten PostgreSQL owner roles reject foreign data access")
    def database_isolation():
        denied = 0
        for name in NAMES:
            source = dotenv_values(RUNTIME / f"{name}-service.env")
            target_name = "academic" if name == "identity" else "identity"
            target = dotenv_values(RUNTIME / f"{target_name}-service.env")
            url = make_url(source["DATABASE_URL"]).set(database=make_url(target["DATABASE_URL"]).database)
            engine = create_engine(url, connect_args={"connect_timeout": 3})
            try:
                with engine.connect() as connection:
                    connection.execute(sql_text("SELECT id FROM departments LIMIT 1" if target_name == "academic" else "SELECT id FROM users LIMIT 1"))
                raise AssertionError(f"{name} role could read foreign owner data")
            except DBAPIError as exc:
                assert getattr(exc.orig, "sqlstate", None) == "42501", f"{name} foreign access failed for an unexpected reason"
                denied += 1
            finally:
                engine.dispose()
        return f"All {denied} service roles denied access to another owner's data by PostgreSQL permissions"

    @case("Security: scoped internal authentication and gateway token integrity")
    def internal():
        key = (RUNTIME / "learning-internal-private.pem").read_text()
        signer = InternalTokenSigner(service_name="learning-service", private_key_pem=key)
        path = f"http://127.0.0.1:8002/api/v1/internal/access/students/{fixtures['student']['id']}/targets"
        good = signer.issue(audience="academic-service", scopes=("academic:relationships:read",))
        assert httpx.get(path, headers={"Authorization": f"Bearer {good}"}, timeout=5).status_code == 200
        bad = signer.issue(audience="academic-service", scopes=())
        assert httpx.get(path, headers={"Authorization": f"Bearer {bad}"}, timeout=5).status_code == 403
        assert httpx.get(path, timeout=5).status_code == 401
        request(None, "GET", "/api/v1/identity/users/me", expected=(401,))
        request(None, "GET", "/api/v1/platform/admin/settings", expected=(401, 403))
        return "Signed service scopes are enforced; anonymous requests cannot impersonate users or services"

    for client in clients.values():
        client.close()
    summary = {status: sum(row["status"] == status for row in records) for status in ("PASS", "FAIL")}
    print(json.dumps(summary), flush=True)
    return int(summary["FAIL"] > 0)


if __name__ == "__main__":
    raise SystemExit(main())
