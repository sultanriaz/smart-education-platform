    @case("Security: twelve PostgreSQL owner roles reject foreign data access")
    def database_isolation():
        denied = 0
        for name in NAMES:
            source = dotenv_values(RUNTIME / f"{name}-service.env")
            target_name = "academic" if name == "identity" else "identity"
            target = dotenv_values(RUNTIME / f"{target_name}-service.env")
            url = make_url(source["DATABASE_URL"]).set(
                database=make_url(target["DATABASE_URL"]).database
            )
            engine = create_engine(url, connect_args={"connect_timeout": 3})
            try:
                with engine.connect() as connection:
                    connection.execute(
                        sql_text(
                            "SELECT id FROM departments LIMIT 1"
                            if target_name == "academic"
                            else "SELECT id FROM users LIMIT 1"
                        )
                    )
                raise AssertionError(f"{name} role could read foreign owner data")
            except DBAPIError as exc:
                assert getattr(exc.orig, "sqlstate", None) == "42501", (
                    f"{name} foreign access failed for an unexpected reason"
                )
                denied += 1
            finally:
                engine.dispose()
        assert denied == len(NAMES) == 12, f"Expected 12 denied roles, got {denied}"
        return f"All {denied} service roles denied access to another owner's data by PostgreSQL permissions"

